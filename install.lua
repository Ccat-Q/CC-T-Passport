  local total, active, revoked, expired = 0, 0, 0, 0
  local now = os.time()
  for _, p in pairs(data.passports) do
    total = total + 1
    if p.status == "revoked" then
      revoked = revoked + 1
    elseif p.expires and now > p.expires then
      expired = expired + 1
    else
      active = active + 1
    end
  end
  return {
    total = total,
    active = active,
    revoked = revoked,
    expired = expired,
    nextID = string.format("PN-%s-%04d", os.date("%Y", os.time()), data.seq),
  }
end

return db
