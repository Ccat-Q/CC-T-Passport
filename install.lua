function net.findServer()
  -- 优先用主机名精确查找
  local id = rednet.lookup(config.DISCOVERY_PROTOCOL, config.DISCOVERY_NAME)
  if id then return id end
  -- 退化为任意注册了该协议的电脑
  local ids = { rednet.lookup(config.DISCOVERY_PROTOCOL) }
  if #ids > 0 then return ids[1] end
  return nil
end

